SET NAMES utf8mb4;
CREATE DATABASE IF NOT EXISTS ledger_sim DEFAULT CHARSET utf8mb4;
USE ledger_sim;
CREATE TABLE `accounts` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `merchant_code` varchar(64) NOT NULL,
  `uid` bigint(20) NOT NULL,
  `token_code` varchar(32) NOT NULL,
  `available` decimal(38,18) NOT NULL,
  `frozen` decimal(38,18) NOT NULL,
  `created_at` datetime(6) NOT NULL,
  `updated_at` datetime(6) NOT NULL,
  KEY `idx_accounts_merchant_token` (`merchant_code`,`token_code`),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_accounts_owner` (`uid`,`token_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `balance_adjustments` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `adjustment_no` bigint(20) NOT NULL,
  `merchant_code` varchar(64) NOT NULL,
  `external_id` varchar(200) NOT NULL,
  `uid` bigint(20) NOT NULL,
  `token_code` varchar(32) NOT NULL,
  `direction` varchar(8) NOT NULL,
  `amount` decimal(38,18) NOT NULL,
  `reason` varchar(32) NOT NULL,
  `reference` varchar(200) NOT NULL,
  `memo` varchar(200) NOT NULL,
  `status` varchar(16) NOT NULL,
  `voucher_no` bigint(20),
  `created_at` datetime(6) NOT NULL,
  `updated_at` datetime(6) NOT NULL,
  KEY `idx_balance_adjustments_merchant_time` (`merchant_code`,`created_at`),
  KEY `idx_balance_adjustments_user` (`uid`,`adjustment_no`),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_balance_adjustments_external` (`merchant_code`,`external_id`),
  UNIQUE KEY `uk_balance_adjustments_no` (`adjustment_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `deposits` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `deposit_no` bigint(20) NOT NULL,
  `channel` varchar(16) NOT NULL,
  `merchant_code` varchar(64) NOT NULL,
  `external_id` varchar(200),
  `uid` bigint(20) NOT NULL,
  `token_code` varchar(32) NOT NULL,
  `address_order_no` bigint(20),
  `network` varchar(20) NOT NULL,
  `address` varchar(200) NOT NULL,
  `memo` varchar(100) NOT NULL,
  `amount` decimal(38,18) NOT NULL,
  `tx_hash` varchar(200) NOT NULL,
  `confirmations` int(11) NOT NULL,
  `required_confirmations` int(11) NOT NULL,
  `status` varchar(16) NOT NULL,
  `cc_status` varchar(20) NOT NULL,
  `voucher_no` bigint(20),
  `cc_created_at` datetime(6) NOT NULL,
  `created_at` datetime(6) NOT NULL,
  `updated_at` datetime(6) NOT NULL,
  KEY `idx_deposits_merchant_time` (`merchant_code`,`created_at`),
  KEY `idx_deposits_tx_hash` (`tx_hash`),
  KEY `idx_deposits_user` (`uid`,`deposit_no`),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_deposits_deposit_no` (`deposit_no`),
  UNIQUE KEY `uk_deposits_external` (`merchant_code`,`external_id`),
  UNIQUE KEY `uk_deposits_tx` (`network`,`tx_hash`,`address`,`memo`,`token_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `invoices` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `invoice_no` bigint(20) NOT NULL,
  `merchant_code` varchar(64) NOT NULL,
  `external_id` varchar(200) NOT NULL,
  `payee_uid` bigint(20) NOT NULL,
  `payer_uid` bigint(20),
  `token_code` varchar(32) NOT NULL,
  `amount` decimal(38,18) NOT NULL,
  `refunded_amount` decimal(38,18) NOT NULL,
  `status` varchar(24) NOT NULL,
  `payment_method` varchar(32) NOT NULL,
  `payee_memo` varchar(200) NOT NULL,
  `payer_memo` varchar(200) NOT NULL,
  `voucher_no` bigint(20),
  `expires_at` datetime(6) NOT NULL,
  `paid_at` datetime(6),
  `created_at` datetime(6) NOT NULL,
  `updated_at` datetime(6) NOT NULL,
  KEY `idx_invoices_expire` (`status`,`expires_at`),
  KEY `idx_invoices_merchant_time` (`merchant_code`,`created_at`),
  KEY `idx_invoices_payee` (`payee_uid`,`invoice_no`),
  KEY `idx_invoices_payer` (`payer_uid`,`invoice_no`),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_invoices_external` (`merchant_code`,`external_id`),
  UNIQUE KEY `uk_invoices_invoice_no` (`invoice_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `journals` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `voucher_no` bigint(20) NOT NULL,
  `biz_type` varchar(32) NOT NULL,
  `biz_no` bigint(20) NOT NULL,
  `token_code` varchar(32) NOT NULL,
  `amount` decimal(38,18) NOT NULL,
  `memo` varchar(200) NOT NULL,
  `created_at` datetime(6) NOT NULL,
  KEY `idx_journals_token` (`token_code`,`biz_type`),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_journals_biz` (`biz_type`,`biz_no`,`token_code`),
  UNIQUE KEY `uk_journals_voucher_no` (`voucher_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `journal_entries` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `entry_no` bigint(20) NOT NULL,
  `voucher_no` bigint(20) NOT NULL,
  `biz_type` varchar(32) NOT NULL,
  `biz_no` bigint(20) NOT NULL,
  `uid` bigint(20) NOT NULL,
  `token_code` varchar(32) NOT NULL,
  `bucket` varchar(10) NOT NULL,
  `amount` decimal(38,18) NOT NULL,
  `balance_after` decimal(38,18) NOT NULL,
  `created_at` datetime(6) NOT NULL,
  KEY `idx_journal_entries_user` (`uid`,`entry_no`),
  KEY `idx_journal_entries_user_token` (`uid`,`token_code`,`entry_no`),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_journal_entries` (`voucher_no`,`uid`,`bucket`),
  UNIQUE KEY `uk_journal_entries_entry_no` (`entry_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `merchants` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `code` varchar(64) NOT NULL,
  `external_code` varchar(64),
  `name` varchar(128) NOT NULL,
  `webhook_url` varchar(512) NOT NULL,
  `allow_create_user` tinyint(1) NOT NULL,
  `allow_create_address` tinyint(1) NOT NULL,
  `allow_balance_adjustment` tinyint(1) NOT NULL,
  `status` varchar(16) NOT NULL,
  `created_at` datetime(6) NOT NULL,
  `updated_at` datetime(6) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_merchants_code` (`code`),
  UNIQUE KEY `uk_merchants_external_code` (`external_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `tokens` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `code` varchar(32) NOT NULL,
  `symbol` varchar(32) NOT NULL,
  `decimals` smallint(6) NOT NULL,
  `icon` varchar(255) NOT NULL,
  `cc_symbol` varchar(32) NOT NULL,
  `status` varchar(16) NOT NULL,
  `created_at` datetime(6) NOT NULL,
  `updated_at` datetime(6) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_tokens_code` (`code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `token_networks` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `token_code` varchar(32) NOT NULL,
  `network` varchar(20) NOT NULL,
  `chain_name` varchar(64) NOT NULL,
  `chain_type` varchar(16) NOT NULL,
  `chain_id` bigint(20) NOT NULL,
  `decimals` smallint(6) NOT NULL,
  `contract_address` varchar(200) NOT NULL,
  `icon` varchar(255) NOT NULL,
  `channel` varchar(16) NOT NULL,
  `memo_required` tinyint(1) NOT NULL,
  `deposit_enabled` tinyint(1) NOT NULL,
  `withdraw_enabled` tinyint(1) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_token_networks` (`token_code`,`network`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `transfers` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `transfer_no` bigint(20) NOT NULL,
  `merchant_code` varchar(64) NOT NULL,
  `external_id` varchar(200) NOT NULL,
  `from_uid` bigint(20) NOT NULL,
  `to_uid` bigint(20) NOT NULL,
  `token_code` varchar(32) NOT NULL,
  `amount` decimal(38,18) NOT NULL,
  `memo` varchar(200) NOT NULL,
  `status` varchar(16) NOT NULL,
  `voucher_no` bigint(20),
  `created_at` datetime(6) NOT NULL,
  `updated_at` datetime(6) NOT NULL,
  KEY `idx_transfers_from` (`from_uid`,`transfer_no`),
  KEY `idx_transfers_merchant_time` (`merchant_code`,`created_at`),
  KEY `idx_transfers_to` (`to_uid`,`transfer_no`),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_transfers_external` (`merchant_code`,`external_id`),
  UNIQUE KEY `uk_transfers_transfer_no` (`transfer_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `users` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `uid` bigint(20) NOT NULL,
  `merchant_code` varchar(64) NOT NULL,
  `external_key` varchar(200) NOT NULL,
  `name` varchar(255) NOT NULL,
  `avatar_url` varchar(512) NOT NULL,
  `profile` json NOT NULL,
  `status` varchar(16) NOT NULL,
  `created_at` datetime(6) NOT NULL,
  `updated_at` datetime(6) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_users_merchant_key` (`merchant_code`,`external_key`),
  UNIQUE KEY `uk_users_uid` (`uid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE `withdrawals` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `withdrawal_no` bigint(20) NOT NULL,
  `merchant_code` varchar(64) NOT NULL,
  `external_id` varchar(200) NOT NULL,
  `uid` bigint(20) NOT NULL,
  `token_code` varchar(32) NOT NULL,
  `network` varchar(20) NOT NULL,
  `address` varchar(200) NOT NULL,
  `memo` varchar(100) NOT NULL,
  `amount` decimal(38,18) NOT NULL,
  `fee` decimal(38,18) NOT NULL,
  `received_amount` decimal(38,18),
  `actual_gas_fee` decimal(38,18),
  `actual_gas_fee_token` decimal(38,18),
  `token_price` decimal(38,18),
  `status` varchar(16) NOT NULL,
  `cc_status` int(11),
  `cc_order_no` varchar(100),
  `cc_trace_id` varchar(100) NOT NULL,
  `tx_hash` varchar(200) NOT NULL,
  `failure_reason` varchar(500) NOT NULL,
  `created_at` datetime(6) NOT NULL,
  `updated_at` datetime(6) NOT NULL,
  KEY `idx_withdrawals_merchant_time` (`merchant_code`,`created_at`),
  KEY `idx_withdrawals_status` (`status`,`created_at`),
  KEY `idx_withdrawals_tx_hash` (`tx_hash`),
  KEY `idx_withdrawals_user` (`uid`,`withdrawal_no`),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_withdrawals_cc_order_no` (`cc_order_no`),
  UNIQUE KEY `uk_withdrawals_external` (`merchant_code`,`external_id`),
  UNIQUE KEY `uk_withdrawals_withdrawal_no` (`withdrawal_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
